"""한국어 활용형 정규식 — 어간만 쓰면 본문에서 가장 흔한 형태를 비껴간다.

같은 함정에 세 번 빠졌다.

1. diff 엔진 — `정하`로 위임을 찾다가 "대통령령으로 **정한다**"를 통째로 놓쳤다.
2. 시행령 페어링 — 새 모듈에서 똑같은 실수를 재현했다.
3. 규모 판정 — `아니하`로 배제 단서를 찾다가 "적용하지 **아니한다**"를 놓쳤다.
   그 결과 "상시 5명 미만은 적용하지 아니한다"가 적용 *조건*으로 분류됐다.

원인은 하나다. 법조문의 종결형은 `~한다`인데 사전형 어간은 `~하`로 끝난다.
어간을 그대로 정규식에 쓰면 조문에 가장 많이 나오는 형태만 정확히 빠진다.

**새로 한국어 용언 패턴이 필요하면 여기에 추가하고 여기서 가져다 쓴다.**
각 모듈에서 따로 쓰면 네 번째가 나온다.
"""

from __future__ import annotations

HADA = r"(?:하|한|할|함|해|했|하여)"
"""'하다'의 활용형. 하다/한다/할/함/해야/했다/하여."""

DELEGATION_VERB = rf"(?:정{HADA}|규정)"
"""'정하다/규정하다'. 정한다·정하는·정할·규정한다 …"""

NOT_DO_VERB = rf"아니{HADA}"
"""'아니하다'. 아니한다·아니하는·아니하고 … 법조문의 부정 종결형."""
